"""XcodeGen project generation for the nucleantui bootstrap.

Xcode is only needed where ``swift run`` cannot go: iOS (device and
simulator), and macOS as a proper signed ``.app`` for the App Store. The
project is one multi-platform app target that compiles the app's Swift sources
where they are and depends on the packages nucleant.toml declares — the shape
of NucleantUI's own ``Examples/xcode/project.yml``. Its ``@main …: NucleantApp``
is the entry point on both platforms; UIKit's scene manifest without a delegate
class lets NucleantUI's launch delegate answer.
"""

from __future__ import annotations

import os.path
from pathlib import Path
from typing import Any

import yaml

from ...bootstrap import XcodeProjectDelegate
from ...config_models import NucleantTomlProtocol
from .spec_merge import merge_user_spec
from .swift_config import SwiftAppConfig

BUNDLE_MODULE_SWIFT = """\
//
//  BundleModule.swift — generated by nucleant.
//
//  SwiftPM gives a package target with resources a `Bundle.module`; an app
//  target in an Xcode project has none, and its resources are in the app's
//  own bundle. This is that accessor, so sources that read their resources
//  through `Bundle.module` build here unchanged.
//

import Foundation

extension Bundle {
    static var module: Bundle { .main }
}
"""

# Info.plist keys every NucleantUI app target needs (from NucleantUI's
# Examples/xcode/project.yml).
_BASE_INFO: dict[str, Any] = {
    "CFBundleDisplayName": "$(PRODUCT_NAME)",
    "CFBundleShortVersionString": "$(MARKETING_VERSION)",
    "CFBundleVersion": "$(CURRENT_PROJECT_VERSION)",
    # iOS. A scene manifest with no delegate class named: UIKit then asks the
    # app delegate for a configuration, and NucleantUI's `_AppLaunchDelegate`
    # answers with its own scene delegate — so `@main` stays plain NucleantApp.
    # The empty UILaunchScreen is the system-generated launch screen; without
    # it iOS runs the app letterboxed at a legacy size.
    "UIApplicationSceneManifest": {"UIApplicationSupportsMultipleScenes": False},
    "UILaunchScreen": {},
    "UIApplicationSupportsIndirectInputEvents": True,
    "UIStatusBarHidden": True,
    "UIViewControllerBasedStatusBarAppearance": False,
    "UIRequiresFullScreen": False,
    "UISupportedInterfaceOrientations": [
        "UIInterfaceOrientationPortrait",
        "UIInterfaceOrientationPortraitUpsideDown",
        "UIInterfaceOrientationLandscapeLeft",
        "UIInterfaceOrientationLandscapeRight",
    ],
    "LSMinimumSystemVersion": "$(MACOSX_DEPLOYMENT_TARGET)",
    "NSHighResolutionCapable": True,
}


class XcodeBuilderError(Exception):
    pass


class NucleantUIXcodeBuilder:
    """Materializes ``project_dist/xcode/`` and runs ``xcodegen``."""

    def __init__(
        self,
        config: NucleantTomlProtocol,
        swift: SwiftAppConfig,
        delegate: XcodeProjectDelegate,
    ) -> None:
        apple = config.apple
        if apple is None or (apple.ios is None and apple.macos is None):
            raise XcodeBuilderError("nucleant.toml has neither [ios] nor [macos]")
        self.config = config
        self.swift = swift
        self.delegate = delegate
        self.working_dir = delegate.working_dir
        self.ios = apple.ios
        self.macos = apple.macos
        self.app_name = config.app_name

    @property
    def project_dir(self) -> Path:
        return self.working_dir / "project_dist" / "xcode"

    @property
    def xcodeproj(self) -> Path:
        return self.project_dir / f"{self.app_name}.xcodeproj"

    # ------------------------------------------------------------------
    # Spec
    # ------------------------------------------------------------------

    def _rel(self, path: Path) -> str:
        return Path(os.path.relpath(path, self.project_dir)).as_posix()

    def _bundle_ids(self) -> tuple[str, str | None]:
        """(the target's bundle id, a macOS-only override when they differ)."""
        ios_id = self.ios.bundle_id if self.ios else None
        mac_id = self.macos.bundle_id if self.macos else None
        primary = ios_id or mac_id or f"org.nucleantui.{self.config.name}"
        return primary, (mac_id if mac_id and mac_id != primary else None)

    def _target(self) -> dict[str, Any]:
        swift = self.swift
        if not swift.sources:
            raise XcodeBuilderError(
                "nucleant.toml [swift] has no sources for the Xcode app target"
            )
        bundle_id, mac_bundle_id = self._bundle_ids()
        team = (self.ios.developer_team if self.ios else None) or (
            self.macos.developer_team if self.macos else None
        )
        destinations = [n for n, d in (("iOS", self.ios), ("macOS", self.macos)) if d]

        info = dict(_BASE_INFO)
        entitlements: dict[str, Any] = {}
        for data in (self.ios, self.macos):  # macOS last: its keys win
            if data is not None:
                info.update(data.info_plist)
                entitlements.update(data.entitlements)

        version_src = self.ios or self.macos
        assert version_src is not None
        settings: dict[str, Any] = {
            "PRODUCT_NAME": self.app_name,
            "PRODUCT_MODULE_NAME": swift.target,
            "PRODUCT_BUNDLE_IDENTIFIER": bundle_id,
            "MARKETING_VERSION": version_src.version,
            "CURRENT_PROJECT_VERSION": version_src.build_number,
            # Sign to run locally by default: all the simulator and macOS need.
            # A real iOS device needs a team ([ios] developer_team).
            "CODE_SIGN_STYLE": "Automatic",
            "DEVELOPMENT_TEAM": team or "",
            "CODE_SIGN_IDENTITY": "-",
            "CODE_SIGN_IDENTITY[sdk=iphoneos*]": "Apple Development",
            "SUPPORTED_PLATFORMS": " ".join(
                (["iphoneos", "iphonesimulator"] if self.ios else [])
                + (["macosx"] if self.macos else [])
            ),
            "TARGETED_DEVICE_FAMILY": "1,2",
            "SUPPORTS_MACCATALYST": "NO",
            "SUPPORTS_MAC_DESIGNED_FOR_IPHONE_IPAD": "NO",
            "SUPPORTS_XR_DESIGNED_FOR_IPHONE_IPAD": "NO",
            # MoltenVK / ThorVG / libomp come as dynamic frameworks from the
            # packages' binary targets; Xcode embeds them here.
            "LD_RUNPATH_SEARCH_PATHS": [
                "$(inherited)",
                "@executable_path/Frameworks",
                "@executable_path/../Frameworks",
            ],
        }
        if mac_bundle_id:
            settings["PRODUCT_BUNDLE_IDENTIFIER[sdk=macosx*]"] = mac_bundle_id
        if swift.unsafe_flags:
            settings["OTHER_SWIFT_FLAGS"] = ["$(inherited)", *swift.unsafe_flags]

        target: dict[str, Any] = {
            "type": "application",
            "platform": "auto",
            "supportedDestinations": destinations,
            "sources": [{"path": self._rel(s)} for s in swift.sources]
            + [{"path": "Support/BundleModule.swift"}],
            "dependencies": [
                {"package": dep.name, "product": product}
                for dep in swift.dependencies
                for product in dep.product_names
            ],
            "settings": {"base": settings},
            "info": {"path": "Support/Info.plist", "properties": info},
            "scheme": {"testTargets": [], "gatherCoverageData": False},
        }
        if entitlements:
            target["entitlements"] = {
                "path": f"Support/{swift.target}.entitlements",
                "properties": entitlements,
            }

        post_scripts = []
        hook = (self.ios.post_build if self.ios else None) or (
            self.macos.post_build if self.macos else None
        )
        if hook is not None:
            runner = "uv run " if hook.suffix == ".py" else ""
            post_scripts.append(
                {
                    "name": "nucleant post-build",
                    "script": (
                        'export PATH="$HOME/.local/bin:$PATH"\n'
                        'cd "$PROJECT_DIR/../.."\n'
                        f'{runner}"{hook.as_posix()}"\n'
                    ),
                }
            )
        if self.config.python_enabled:
            post_scripts.extend(self._python_build_phases())
        if post_scripts:
            target["postBuildScripts"] = post_scripts
        return target

    def _python_build_phases(self) -> list[dict[str, Any]]:
        """Install the stdlib + site_packages into the bundle (Python layer)."""
        from ...python.xcode_python_target import install_py_modules_script

        return [
            {
                "name": "Install Python modules",
                "script": install_py_modules_script(
                    uv_python=self.delegate.uv_py_version,
                    py_version=self.delegate.py_version,
                ),
            }
        ]

    def build_spec(self) -> dict[str, Any]:
        swift = self.swift
        bundle_id, _ = self._bundle_ids()
        prefix = bundle_id.rsplit(".", 1)[0] if "." in bundle_id else bundle_id
        deployment: dict[str, str] = {}
        if self.ios:
            deployment["iOS"] = swift.ios_deployment
        if self.macos:
            deployment["macOS"] = swift.macos_deployment
        spec: dict[str, Any] = {
            "name": self.app_name,
            "options": {
                "bundleIdPrefix": prefix,
                "deploymentTarget": deployment,
            },
            "packages": {
                dep.name: dep.as_xcodegen_package(self.project_dir)
                for dep in swift.dependencies
            },
            "settings": {
                "base": {
                    "SWIFT_VERSION": "6.0",
                    "ENABLE_USER_SCRIPT_SANDBOXING": "NO"
                    if self.config.python_enabled
                    else "YES",
                }
            },
            "targets": {self.app_name: self._target()},
        }
        return merge_user_spec(spec, self.working_dir)

    # ------------------------------------------------------------------
    # Generation
    # ------------------------------------------------------------------

    def _write_support(self) -> None:
        support = self.project_dir / "Support"
        support.mkdir(parents=True, exist_ok=True)
        (support / "BundleModule.swift").write_text(BUNDLE_MODULE_SWIFT, encoding="utf-8")

    def _write_spec(self) -> tuple[Path, bool]:
        """Write project.yml; returns (path, whether it changed)."""
        spec_path = self.project_dir / "project.yml"
        text = yaml.safe_dump(self.build_spec(), sort_keys=False)
        changed = not spec_path.is_file() or spec_path.read_text() != text
        if changed:
            spec_path.write_text(text)
        return spec_path, changed

    def generate(self, force: bool = False) -> Path:
        """Write the spec and (re)run xcodegen when it changed. Returns the .xcodeproj."""
        self.project_dir.mkdir(parents=True, exist_ok=True)
        self._write_support()
        spec_path, changed = self._write_spec()
        if changed or force or not self.xcodeproj.exists():
            self.delegate.xcode_generate(spec_path=spec_path, project_dir=self.project_dir)
        if not self.xcodeproj.exists():
            raise XcodeBuilderError(f"xcodegen succeeded but {self.xcodeproj} not found")
        return self.xcodeproj
